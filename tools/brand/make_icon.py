#!/usr/bin/env python3
"""Generates the Refocal mark (docs/spec/appendix/brand.md: focus ring with ticks around a 3x3
pixel grid that turns into a sharp circle at the centre; white on the brand gradient).

Outputs, all from the same geometry:
  assets/brand/refocal-mark.svg, assets/brand/refocal-icon.svg   (CC BY 4.0)
  app/android/app/src/main/res/drawable/ic_launcher_{foreground,background}.xml
  app/android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml (adaptive + monochrome)
  fastlane/metadata/android/en-US/images/icon.png (512 px, needs Pillow)

Usage: tools/brand/make_icon.py
"""
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
VIEW = 108.0  # adaptive icon canvas, dp; the safe zone is the central 66 dp circle
C = VIEW / 2
PRIMARY, SECONDARY = "#3D5AFE", "#00BFA5"

RING_R, RING_W = 23.0, 3.0
TICKS, TICK_IN, TICK_OUT, TICK_W = 48, 26.0, 30.0, 1.5
CELL_STEP = 10.0
# Cell half-size by distance from the centre: corners are the smallest pixels; the centre is a
# circle (focus).
CORNER_H, EDGE_H, CENTRE_R = 2.6, 3.4, 4.6


def circle(cx, cy, r):
    return (f"M{cx - r:.2f},{cy:.2f}a{r:.2f},{r:.2f} 0 1,0 {2 * r:.2f},0"
            f"a{r:.2f},{r:.2f} 0 1,0 {-2 * r:.2f},0z")


def ring_path():
    outer, inner = RING_R + RING_W / 2, RING_R - RING_W / 2
    return circle(C, C, outer) + circle(C, C, inner)  # even-odd: a ring


def rect(cx, cy, h):
    return f"M{cx - h:.2f},{cy - h:.2f}h{2 * h:.2f}v{2 * h:.2f}h{-2 * h:.2f}z"


def ticks_path():
    parts = []
    for i in range(TICKS):
        a = 2 * math.pi * i / TICKS
        dx, dy = math.cos(a), math.sin(a)
        nx, ny = -dy * TICK_W / 2, dx * TICK_W / 2
        p = [(C + dx * TICK_IN + nx, C + dy * TICK_IN + ny),
             (C + dx * TICK_OUT + nx, C + dy * TICK_OUT + ny),
             (C + dx * TICK_OUT - nx, C + dy * TICK_OUT - ny),
             (C + dx * TICK_IN - nx, C + dy * TICK_IN - ny)]
        parts.append("M" + "L".join(f"{x:.2f},{y:.2f}" for x, y in p) + "z")
    return "".join(parts)


def grid_path():
    parts = []
    for gy in (-1, 0, 1):
        for gx in (-1, 0, 1):
            x, y = C + gx * CELL_STEP, C + gy * CELL_STEP
            if gx == gy == 0:
                parts.append(circle(x, y, CENTRE_R))
            else:
                parts.append(rect(x, y, CORNER_H if gx and gy else EDGE_H))
    return "".join(parts)


MARK = [ring_path(), ticks_path(), grid_path()]


def write(rel, text):
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", rel)


def svg(background):
    bg = ""
    if background:
        bg = (f'<defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">'
              f'<stop offset="0" stop-color="{PRIMARY}"/><stop offset="1" stop-color="{SECONDARY}"/>'
              f'</linearGradient></defs><rect width="{VIEW:g}" height="{VIEW:g}" fill="url(#g)"/>')
    fill = "#FFFFFF" if background else PRIMARY
    paths = "".join(f'<path fill-rule="evenodd" fill="{fill}" d="{d}"/>' for d in MARK)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {VIEW:g} {VIEW:g}">'
            f"<!-- Refocal mark, CC BY 4.0. Generated by tools/brand/make_icon.py -->{bg}{paths}</svg>\n")


def vector(paths, header=""):
    return ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Generated by tools/brand/make_icon.py; edit the script, not this file. -->\n"
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    xmlns:aapt="http://schemas.android.com/aapt"\n'
            f'    android:width="{VIEW:g}dp" android:height="{VIEW:g}dp"\n'
            f'    android:viewportWidth="{VIEW:g}" android:viewportHeight="{VIEW:g}">\n'
            f"{header}{paths}</vector>\n")


def android():
    fg = "".join(f'    <path android:fillType="evenOdd" android:fillColor="#FFFFFF"\n'
                 f'        android:pathData="{d}" />\n' for d in MARK)
    write("app/android/app/src/main/res/drawable/ic_launcher_foreground.xml", vector(fg))
    bg = (f'    <path android:pathData="M0,0h{VIEW:g}v{VIEW:g}h-{VIEW:g}z">\n'
          '        <aapt:attr name="android:fillColor">\n'
          f'            <gradient android:type="linear" android:startX="0" android:startY="0"\n'
          f'                android:endX="{VIEW:g}" android:endY="{VIEW:g}">\n'
          f'                <item android:offset="0" android:color="{PRIMARY}" />\n'
          f'                <item android:offset="1" android:color="{SECONDARY}" />\n'
          "            </gradient>\n        </aapt:attr>\n    </path>\n")
    write("app/android/app/src/main/res/drawable/ic_launcher_background.xml", vector(bg))
    write("app/android/app/src/main/res/mipmap-anydpi-v26/ic_launcher.xml",
          '<?xml version="1.0" encoding="utf-8"?>\n'
          "<!-- Generated by tools/brand/make_icon.py. minSdk 29: no raster fallbacks needed. -->\n"
          '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          '    <background android:drawable="@drawable/ic_launcher_background" />\n'
          '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
          '    <monochrome android:drawable="@drawable/ic_launcher_foreground" />\n'
          "</adaptive-icon>\n")


def png(rel, size):
    """Full-bleed square icon (F-Droid masks it itself), rendered at 4x and downsampled."""
    from PIL import Image, ImageDraw

    s = size * 4
    k = s / VIEW
    img = Image.new("RGB", (s, s))
    a, b = (int(PRIMARY[i:i + 2], 16) for i in (1, 3, 5)), (int(SECONDARY[i:i + 2], 16) for i in (1, 3, 5))
    a, b = list(a), list(b)
    px = img.load()
    for y in range(s):
        for x in range(s):
            t = (x + y) / (2 * (s - 1))
            px[x, y] = tuple(round(a[i] + (b[i] - a[i]) * t) for i in range(3))
    d = ImageDraw.Draw(img)
    w = "#FFFFFF"
    d.ellipse([(C - RING_R - RING_W / 2) * k, (C - RING_R - RING_W / 2) * k,
               (C + RING_R + RING_W / 2) * k, (C + RING_R + RING_W / 2) * k], outline=w,
              width=round(RING_W * k))
    for i in range(TICKS):
        an = 2 * math.pi * i / TICKS
        dx, dy = math.cos(an), math.sin(an)
        nx, ny = -dy * TICK_W / 2, dx * TICK_W / 2
        d.polygon([((C + dx * TICK_IN + nx) * k, (C + dy * TICK_IN + ny) * k),
                   ((C + dx * TICK_OUT + nx) * k, (C + dy * TICK_OUT + ny) * k),
                   ((C + dx * TICK_OUT - nx) * k, (C + dy * TICK_OUT - ny) * k),
                   ((C + dx * TICK_IN - nx) * k, (C + dy * TICK_IN - ny) * k)], fill=w)
    for gy in (-1, 0, 1):
        for gx in (-1, 0, 1):
            x, y = C + gx * CELL_STEP, C + gy * CELL_STEP
            h = CENTRE_R if gx == gy == 0 else (CORNER_H if gx and gy else EDGE_H)
            box = [(x - h) * k, (y - h) * k, (x + h) * k, (y + h) * k]
            (d.ellipse if gx == gy == 0 else d.rectangle)(box, fill=w)
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    img.resize((size, size), Image.LANCZOS).save(p, optimize=True)
    print("wrote", rel)


if __name__ == "__main__":
    write("assets/brand/refocal-mark.svg", svg(background=False))
    write("assets/brand/refocal-icon.svg", svg(background=True))
    android()
    png("fastlane/metadata/android/en-US/images/icon.png", 512)
